// Shared configuration for every Myriad module. Module specific logic lives in <module>/build.gradle.kts.

val mindustryVersion = property("mindustryVersion") as String
val arcVersion = property("arcVersion") as String

subprojects {
    apply(plugin = "java-library")
    apply(plugin = "maven-publish")

    repositories {
        mavenCentral()
        maven("https://raw.githubusercontent.com/Zelaux/MindustryRepo/master/repository")
        maven("https://maven.xpdustry.com/mindustry")
        maven("https://jitpack.io")
    }

    dependencies {
        // Provided by the game at runtime, never bundled.
        "compileOnly"("com.github.Anuken.Arc:arc-core:$arcVersion")
        "compileOnly"("com.github.Anuken.Mindustry:core:$mindustryVersion")
    }

    // Mindustry pulls its own Arc, keep it in sync with ours.
    configurations.all {
        resolutionStrategy.eachDependency {
            if (requested.group == "com.github.Anuken.Arc") useVersion(arcVersion)
        }
    }

    configure<JavaPluginExtension> {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
        withSourcesJar()
        // withJavadocJar()
    }

    // Per-project source set configuration
    when (project.name) {
        "acari" -> {
            configure<JavaPluginExtension> {
                sourceSets.named("main") { java.setSrcDirs(listOf("src")) }
            }
        }
        "papilio" -> {
            configure<JavaPluginExtension> {
                sourceSets.named("main") { java.setSrcDirs(listOf("src")) }
            }
        }
    }



    // Optional mod.hjson generation for acari module.
    if (project.name == "acari") {
        abstract class ModHjson : DefaultTask() {
            @get:Input abstract val displayName: Property<String>
            @get:Input abstract val modName: Property<String>
            @get:Input abstract val author: Property<String>
            @get:Input abstract val desc: Property<String>
            @get:Input abstract val modVersion: Property<String>
            @get:Input abstract val main: Property<String>
            @get:Input abstract val minGameVersion: Property<Int>
            @get:Input abstract val hidden: Property<Boolean>
            @get:OutputFile abstract val outputFile: RegularFileProperty
            @TaskAction

            fun generate() {
                fun str(s: String) = "\""+ s.replace("\\","\\\\").replace("\"","\\\"").replace("\n","\\n") + "\""
                val out = outputFile.get().asFile
                out.parentFile.mkdirs()
                out.writeText(buildString {
                    appendLine("// GENERATED by ${project.path}:$name, do not edit.")
                    appendLine("displayName: ${str(displayName.get())}")
                    appendLine("name: ${str(modName.get())}")
                    appendLine("author: ${str(author.get())}")
                    appendLine("main: ${str(main.get())}")
                    appendLine("description: ${str(desc.get())}")
                    appendLine("version: ${str(modVersion.get())}")
                    appendLine("minGameVersion: ${minGameVersion.get()}")
                    appendLine("java: true")
                    if (hidden.get()) appendLine("hidden: true")
                })
            }
        }
		
        val hjson by tasks.registering(ModHjson::class) {
            displayName = rootProject.property("mod.displayName").toString()
            modName = project.projectDir.name
            author = rootProject.property("mod.author").toString()
            desc = rootProject.property("mod.description").toString()
            modVersion = project.version.toString()
            main = rootProject.property("mod.main").toString()
            minGameVersion = rootProject.property("mod.minGameVersion").toString().toInt()
            hidden = rootProject.property("mod.hidden").toString().toBoolean()
            outputFile = rootProject.layout.projectDirectory.file("mod.hjson")
        }
		
        tasks.named("processResources") { dependsOn(hjson) }
    }

    tasks.withType<JavaCompile>().configureEach {
        options.encoding = "UTF-8"
        options.release = 17
    }

    // tasks.withType<Javadoc>().configureEach {
    //     (options as StandardJavadocDocletOptions).apply {
    //         addStringOption("Xdoclint:none", "-quiet")
    //         addStringOption("-release", "17")
    //     }
    // }

    // Published as com.github.JP16D.Myriad:<module>:<version>
    configure<PublishingExtension> {
        publications {
            create<MavenPublication>("maven") {
                from(components["java"])
            }
        }
    }
}

// Root-level task to run deploy on all subprojects that support it
tasks.register("deployAll") {
    group = "myriad"
    description = "Builds deploy jars for all applicable subprojects"
    subprojects.forEach { subproject ->
        if (subproject.tasks.findByName("deploy") != null) {
            dependsOn(subproject.tasks.named("deploy"))
        }
    }
}

// Hook deployAll into build lifecycle via subprojects
subprojects {
    tasks.named("build") { dependsOn(rootProject.tasks.named("deployAll")) }
}
